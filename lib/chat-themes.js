export function getChatTheme(themeId) {
  return CHAT_THEMES[themeId] ?? CHAT_THEMES.light;
}

/** @param {string} themeId @param {string} brandColor */
export function resolveChatTheme(themeId, brandColor) {
  const theme = getChatTheme(themeId);
  return {
    ...theme,
    brandColor,
    userBubble: brandColor,
    userText: "#ffffff",
  };
}
